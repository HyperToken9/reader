// PROTOTYPE 48 (throwaway): turn Blitz's Node engine (ref/, copied from origin/dev
// app/electron/speech) into browser modules with the smallest possible patch, and vendor
// onnxruntime-web + npm phonemizer into the extension. Run by setup.sh.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync } from "node:fs";
const here = new URL("..", import.meta.url).pathname;
const ext = here + "extension/";
const nm = here + "node_modules/";

const sub = (s, from, to) => {
  if (!s.includes(from)) throw new Error("patch anchor missing: " + from.slice(0, 60));
  return s.replace(from, to);
};

// engine.js: the only Node-isms are the imports, readFileSync in loadVoices and the
// hard-wired CPU session options. Everything else (windows, pauses, alignment) is untouched.
let e = readFileSync(here + "ref/engine.js", "utf8");
e = sub(e, 'import { readFileSync } from "node:fs";\nimport ort from "ort-speech";\nimport { VOCAB } from "./phonemize.js";',
  '// PROTOTYPE 48: generated by scripts/make_browser.mjs from app/electron/speech/engine.js (origin/dev).\nimport * as ort from "./ort/ort.webgpu.min.mjs";\nimport { VOCAB } from "./phonemize.browser.js";\nimport { Buffer } from "./buffer-shim.js";\nexport { ort };');
e = sub(e, "export function loadVoices(path) {\n  const buf = readFileSync(path);", "export function loadVoices(bytes) {\n  const buf = Buffer.from(bytes);");
e = sub(e, "static async create({ model, voices, phonemize, threads }) {\n    const k = new Kokoro();\n    k.sess = await ort.InferenceSession.create(model, {\n      executionProviders: [\"cpu\"],\n      intraOpNumThreads: threads,\n      interOpNumThreads: 1,\n",
  "static async create({ model, voices, phonemize, threads, executionProviders }) {\n    const k = new Kokoro();\n    k.sess = await ort.InferenceSession.create(model, {\n      executionProviders,\n");
writeFileSync(ext + "engine.browser.js", e);

// phonemize.js: VOCAB via fetch instead of require; makePhonemize is used as is.
let p = readFileSync(here + "ref/phonemize.js", "utf8");
p = sub(p, 'import { createRequire } from "node:module";\n\nconst require = createRequire(import.meta.url);\nexport const VOCAB = require("./vocab.json");',
  '// PROTOTYPE 48: generated by scripts/make_browser.mjs from app/electron/speech/phonemize.js (origin/dev).\nexport const VOCAB = await (await fetch(new URL("./vocab.json", import.meta.url))).json();');
writeFileSync(ext + "phonemize.browser.js", p);
copyFileSync(here + "ref/vocab.json", ext + "vocab.json");

// vendored, not committed
mkdirSync(ext + "ort", { recursive: true });
for (const f of readdirSync(nm + "onnxruntime-web/dist"))
  if (/^ort\.webgpu\.min\.mjs$|^ort-wasm-simd-threaded\.(asyncify|jsep)?\.?(mjs|wasm)$/.test(f)) copyFileSync(nm + "onnxruntime-web/dist/" + f, ext + "ort/" + f);
mkdirSync(ext + "vendor", { recursive: true });
copyFileSync(nm + "phonemizer/dist/phonemizer.js", ext + "vendor/phonemizer.js");
// kokoro-js 1.2.1's own phonemize(), as extracted by prototype 17 (kokorojs_phon.mjs)
const kj = readFileSync(here + "ref/kokorojs_phon.mjs", "utf8");
writeFileSync(ext + "vendor/kokorojs_phon.js", sub(kj, 'from "phonemizer"', 'from "./phonemizer.js"'));
console.log("ort files:", readdirSync(ext + "ort").join(" "));
